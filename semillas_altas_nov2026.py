def main():
    path = ROOT / 'seeds_used.json'
    catalog = json.loads(path.read_text(encoding='utf-8')) if path.exists() else {
        'schema_version': 1, 'season': SEASON, 'divisions': {}}
    if catalog.get('schema_version') != 1 or catalog.get('season') != SEASON:
        raise SystemExit('El catálogo existente no corresponde a noviembre de 2026')
    divisions = catalog.setdefault('divisions', {})
    used = {seed['tag']: slug for slug, div in divisions.items()
            for seed in div.get('seeds', [])}
    for slug, raw in TAGS.items():
        tags = raw.split()
        if len(tags) != len(set(tags)) or not all(re.fullmatch(r'#[0289PYLQGRJCUV]+', t) for t in tags):
            raise SystemExit(f'Tags inválidos o duplicados en {slug}')
        for tag in tags:
            if tag in used and used[tag] != slug:
                raise SystemExit(f'Conflicto de división: {tag} ({used[tag]} / {slug})')
        name = {'legend': 'Legend League', 'champion-1': 'Champion League I',
                'titan-3': 'Titan League III', 'titan-2': 'Titan League II',
                'titan-1': 'Titan League I'}[slug]
        historical = f'https://clashspot.net/en/rankings/clan-war-leagues/{SEASON}-01/{slug}'
        prior = divisions.get(slug)
        if prior and (prior['name'] != name or prior['source_url'] != historical):
            raise SystemExit(f'La procedencia histórica existente de {slug} no coincide')
        existing = prior.get('seeds', []) if prior else []
        merged = existing + [{'tag': tag} for tag in tags if tag not in {s['tag'] for s in existing}]
        if len(merged) > 200:
            raise SystemExit(f'{slug}: el catálogo superaría 200 semillas')
        ids = {'champion-1': '48000018', 'titan-3': '48000019',
               'titan-2': '48000020', 'titan-1': '48000021', 'legend': '48000022'}
        evidence = json.dumps({'ranking_url': RANKING + ids[slug],
                               'season_detail': SEASON + '-01', 'tags': tags}, sort_keys=True).encode()
        divisions[slug] = {**(prior or {}), 'name': name, 'source_url': historical,
            'evidence_sha256': (prior or {}).get('evidence_sha256') or hashlib.sha256(evidence).hexdigest(),
            'ranking_capture_url': RANKING + ids[slug],
            'captured_at_utc': datetime.now(timezone.utc).isoformat(), 'seeds': merged}
        print(f'{name}: {len(merged)} semillas (antes {len(existing)})')
    ROOT.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix('.json.tmp')
    tmp.write_text(json.dumps(catalog, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    tmp.replace(path)
    print('Catálogo actualizado:', path)


if __name__ == '__main__':
    main()
